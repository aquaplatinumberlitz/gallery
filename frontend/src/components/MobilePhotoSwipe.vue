<script setup lang="ts">
import { computed, nextTick, toRef, useTemplateRef, watch } from "vue";
import { Info, X, ScanSearch } from "lucide-vue-next";
import "photoswipe/dist/photoswipe.css";
import type { FileNode } from "../types";
import { usePhotoSwipe } from "../composables/usePhotoSwipe";

const props = defineProps<{
  items: FileNode[];
  currentIndex: number;
  isOpen: boolean;
  metadataOpen?: boolean;
  canFindRelated?: boolean;
}>();

const emit = defineEmits<{
  (e: "close"): void;
  (e: "indexChange", index: number): void;
  (e: "toggleMetadata"): void;
  (e: "findRelated"): void;
}>();

const containerRef = useTemplateRef<HTMLElement>("container");
const metadataButtonRef = useTemplateRef<HTMLButtonElement>("metadataButton");
const counter = computed(() => `${props.currentIndex + 1} / ${props.items.length}`);

usePhotoSwipe({
  containerRef,
  items: computed(() => props.items),
  currentIndex: toRef(props, "currentIndex"),
  isOpen: toRef(props, "isOpen"),
  photoSwipeOptions: {
    closeOnVerticalDrag: true,
    allowPanToNext: true,
    trapFocus: false,
    returnFocus: false,
  },
  thumbnailSize: 1600,
  onIndexChange: (index) => emit("indexChange", index),
  onClose: () => emit("close"),
});

watch(
  () => props.metadataOpen,
  async (isOpen, wasOpen) => {
    if (!wasOpen || isOpen) return;
    await nextTick();
    metadataButtonRef.value?.focus({ preventScroll: true });
  },
);
</script>

<template>
  <div ref="container" class="mobile-photoswipe-container" />
  <div class="mobile-photoswipe-counter">
    {{ counter }}
  </div>
  <button class="lx-ctrl mobile-photoswipe-close" aria-label="Close" @click="emit('close')">
    <X :size="22" :stroke-width="2.2" />
  </button>
  <button
    v-if="!metadataOpen && canFindRelated"
    class="lx-ctrl mobile-photoswipe-find-related"
    aria-label="Find related"
    @click.stop="emit('findRelated')"
  >
    <ScanSearch :size="22" :stroke-width="2.2" />
  </button>
  <button
    v-if="!metadataOpen"
    ref="metadataButton"
    class="lx-ctrl mobile-photoswipe-info"
    :aria-label="'View image info'"
    @click.stop="emit('toggleMetadata')"
  >
    <Info :size="22" :stroke-width="2.2" />
  </button>
</template>

