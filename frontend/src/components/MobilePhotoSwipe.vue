<script setup lang="ts">
import { ref, computed, toRef } from "vue";
import { Info } from "lucide-vue-next";
import "photoswipe/dist/photoswipe.css";
import type { FileNode } from "../types";
import { usePhotoSwipe } from "../composables/usePhotoSwipe";

const props = defineProps<{
  items: FileNode[];
  currentIndex: number;
  isOpen: boolean;
  metadataOpen?: boolean;
}>();

const emit = defineEmits<{
  (e: "close"): void;
  (e: "indexChange", index: number): void;
  (e: "toggleMetadata"): void;
}>();

const containerRef = ref<HTMLElement | null>(null);

usePhotoSwipe({
  containerRef,
  items: computed(() => props.items),
  currentIndex: toRef(props, "currentIndex"),
  isOpen: toRef(props, "isOpen"),
  photoSwipeOptions: {
    closeOnVerticalDrag: true,
    allowPanToNext: true,
  },
  thumbnailSize: 1600,
  onIndexChange: (index) => emit("indexChange", index),
  onClose: () => emit("close"),
});
</script>

<template>
  <div ref="containerRef" class="mobile-photoswipe-container" />
  <button
    v-if="!metadataOpen"
    class="lightbox-floating-control lightbox-floating-control--mobile"
    :aria-label="'View image info'"
    @click.stop="emit('toggleMetadata')"
  >
    <Info :size="22" :stroke-width="2.2" />
  </button>
</template>

<style scoped lang="scss">
.mobile-photoswipe-container {
  position: fixed;
  inset: 0;
  z-index: 1;
}

.lightbox-floating-control--mobile {
  position: fixed;
  right: max(18px, env(safe-area-inset-right) + 14px);
  bottom: max(24px, env(safe-area-inset-bottom) + 12px);
  z-index: 5000;
}
</style>

